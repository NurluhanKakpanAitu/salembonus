const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { kk, ru }

export type TranslateVars = Record<string, string | number>

export function translate(lang: Language, key: TranslationKey, vars?: TranslateVars): string {
  const text = DICTIONARIES[lang][key] ?? kk[key] ?? key
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match))
}

export type Translator = (key: TranslationKey, vars?: TranslateVars) => string

/** Компоненттерде қолданылатын аударма функциясы. Тіл ауысқанда бет өзі жаңарады. */
export function useT(): Translator {
  const [lang] = useLanguage()
  return (key, vars) => translate(lang, key, vars)
}
